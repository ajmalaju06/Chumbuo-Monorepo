/**
 * Builds the brand kit from the leaf artwork in assets/brand.
 *
 * - Cleans the source mark (solid alpha, trimmed) → public/brand/chumbuo-mark*.png
 * - Lockups (horizontal/stacked × light/dark) as SVG (mark embedded) + PNG
 * - Favicon, Apple touch icon, app icons and social avatar
 *
 * Run: pnpm brand:export
 */
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const SOURCE = join(ROOT, "assets/brand/chumbuo-mark-source.png");
const BRAND_DIR = join(ROOT, "public/brand");
const OATMEAL = "#E8DCC6";
const PINE = "#1F3B2E";
const TAGLINE = "Little moments. Lasting stories.";

/**
 * The artwork's leaves are ~90% opaque, which lets dark surfaces tint through.
 * Snap near-opaque pixels to fully opaque; keep soft edges for anti-aliasing.
 */
async function cleanMark() {
  const { data, info } = await sharp(SOURCE)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  for (let i = 3; i < data.length; i += 4) {
    if (data[i] >= 200) data[i] = 255;
  }
  const solid = await sharp(data, { raw: info }).png().toBuffer();
  const trimmed = await sharp(solid).trim({ threshold: 1 }).png().toBuffer();
  const meta = await sharp(trimmed).metadata();
  // Small breathing room so curls and tips never touch the image edge.
  const pad = Math.round(Math.max(meta.width!, meta.height!) * 0.015);
  return sharp(trimmed)
    .extend({
      top: pad,
      bottom: pad,
      left: pad,
      right: pad,
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png({ compressionLevel: 9 })
    .toBuffer();
}

/** Mark centred on a square tile (`bg` null = transparent). */
async function tile(mark: Buffer, size: number, fill: number, bg: string | null, radius = 0) {
  const inner = Math.round(size * fill);
  const fitted = await sharp(mark)
    .resize(inner, inner, { fit: "inside", kernel: "lanczos3" })
    .toBuffer();
  const base = bg
    ? Buffer.from(
        `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><rect width="${size}" height="${size}" rx="${size * radius}" fill="${bg}"/></svg>`,
      )
    : {
        create: {
          width: size,
          height: size,
          channels: 4 as const,
          background: { r: 0, g: 0, b: 0, alpha: 0 },
        },
      };
  return sharp(base as Buffer)
    .composite([{ input: fitted, gravity: "center" }])
    .png({ compressionLevel: 9 })
    .toBuffer();
}

async function main() {
  // Generated modules must exist before importing the SVG builders.
  const mark = await cleanMark();
  const meta = await sharp(mark).metadata();
  writeFileSync(
    join(ROOT, "lib/brand/mark.generated.ts"),
    `// AUTO-GENERATED by scripts/brand/export-assets.ts — do not edit by hand.
export const MARK = {
  src: "/brand/chumbuo-mark.png",
  width: ${meta.width},
  height: ${meta.height},
} as const;
`,
  );
  const { horizontalSvg, stackedSvg, wordmarkSvg } = await import("../../lib/brand/svg");

  rmSync(BRAND_DIR, { recursive: true, force: true });
  mkdirSync(BRAND_DIR, { recursive: true });

  writeFileSync(join(BRAND_DIR, "chumbuo-mark.png"), mark);
  for (const w of [512, 256]) {
    writeFileSync(
      join(BRAND_DIR, `chumbuo-mark-${w}.png`),
      await sharp(mark).resize({ width: w }).png({ compressionLevel: 9 }).toBuffer(),
    );
  }

  // Lockup SVGs embed a modest-resolution mark to keep files small.
  const embedded = await sharp(mark).resize({ width: 600 }).png({ compressionLevel: 9 }).toBuffer();
  const href = `data:image/png;base64,${embedded.toString("base64")}`;
  const lockups: Record<string, [string, string]> = {
    "chumbuo-horizontal-light": [horizontalSvg(href, "light"), OATMEAL],
    "chumbuo-horizontal-dark": [horizontalSvg(href, "dark"), PINE],
    "chumbuo-stacked-light": [stackedSvg(href, "light", TAGLINE), OATMEAL],
    "chumbuo-stacked-dark": [stackedSvg(href, "dark", TAGLINE), PINE],
  };
  for (const [name, [content]] of Object.entries(lockups)) {
    writeFileSync(join(BRAND_DIR, `${name}.svg`), content);
    // Transparent PNG at print-friendly resolution.
    writeFileSync(
      join(BRAND_DIR, `${name}.png`),
      await sharp(Buffer.from(content), { density: 600 })
        .resize({ width: 2400 })
        .png({ compressionLevel: 9 })
        .toBuffer(),
    );
  }
  writeFileSync(join(BRAND_DIR, "chumbuo-wordmark-light.svg"), wordmarkSvg("light"));
  writeFileSync(join(BRAND_DIR, "chumbuo-wordmark-dark.svg"), wordmarkSvg("dark"));

  // App + social icons on an oatmeal tile.
  writeFileSync(
    join(BRAND_DIR, "chumbuo-app-icon-512.png"),
    await tile(mark, 512, 0.78, OATMEAL, 0.22),
  );
  writeFileSync(
    join(BRAND_DIR, "chumbuo-app-icon-192.png"),
    await tile(mark, 192, 0.78, OATMEAL, 0.22),
  );
  writeFileSync(join(BRAND_DIR, "chumbuo-avatar-512.png"), await tile(mark, 512, 0.72, OATMEAL));

  // Next.js file-convention icons: transparent favicon, square Apple icon.
  rmSync(join(ROOT, "app/icon.svg"), { force: true });
  writeFileSync(join(ROOT, "app/icon.png"), await tile(mark, 64, 1, null));
  writeFileSync(join(ROOT, "app/apple-icon.png"), await tile(mark, 180, 0.8, OATMEAL));

  console.log(`mark ${meta.width}×${meta.height}; exported lockups, icons and avatar`);
}

main();
