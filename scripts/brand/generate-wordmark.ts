/**
 * Traces the "Chumbuo" wordmark from Cormorant Garamond into static SVG path
 * data so the logo never depends on a webfont being loaded.
 *
 * Output: lib/brand/wordmark.generated.ts
 * Run:    pnpm brand:wordmark
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import opentype from "opentype.js";

const ROOT = process.cwd();
const FONT = join(
  ROOT,
  "node_modules/@fontsource/cormorant-garamond/files/cormorant-garamond-latin-500-normal.woff",
);
const OUT = join(ROOT, "lib/brand/wordmark.generated.ts");

const TEXT = "Chumbuo";
const FONT_SIZE = 100;
// Slightly tighter than the font's default spacing — reads as a mark, not a word.
const TRACKING = -2.5;

const buf = readFileSync(FONT);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const scale = FONT_SIZE / font.unitsPerEm;
const baseline = font.ascender * scale;

// opentype's own toPathData() flips Y by default and its rounding emits NaN
// for some values in v2, so serialise the commands ourselves.
const n = (v: number) => String(Math.round(v * 100) / 100);
function toD(path: opentype.Path) {
  return path.commands
    .map((c) => {
      switch (c.type) {
        case "M":
        case "L":
          return `${c.type}${n(c.x)} ${n(c.y)}`;
        case "Q":
          return `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`;
        case "C":
          return `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`;
        case "Z":
          return "Z";
      }
    })
    .join("");
}

let x = 0;
const parts: string[] = [];
let lastO: { x1: number; y1: number; x2: number; y2: number } | null = null;

const glyphs = font.stringToGlyphs(TEXT);
glyphs.forEach((glyph, i) => {
  const path = glyph.getPath(x, baseline, FONT_SIZE);
  parts.push(toD(path));
  if (i === glyphs.length - 1) lastO = path.getBoundingBox();
  const next = glyphs[i + 1];
  const kern = next ? font.getKerningValue(glyph, next) * scale : 0;
  x += (glyph.advanceWidth ?? 0) * scale + kern + (next ? TRACKING : 0);
});

const all = font.getPath(TEXT, 0, baseline, FONT_SIZE);
const box = all.getBoundingBox();
const o = lastO as unknown as { x1: number; y1: number; x2: number; y2: number };

const file = `// AUTO-GENERATED by scripts/brand/generate-wordmark.ts — do not edit by hand.
export const WORDMARK = {
  d: ${JSON.stringify(parts.join(""))},
  width: ${Math.ceil(x)},
  top: ${Math.floor(box.y1)},
  bottom: ${Math.ceil(box.y2)},
  /** Bounding box of the final "o" — the petal sits in its counter. */
  finalO: { x1: ${o.x1.toFixed(2)}, y1: ${o.y1.toFixed(2)}, x2: ${o.x2.toFixed(2)}, y2: ${o.y2.toFixed(2)} },
} as const;
`;
writeFileSync(OUT, file);
console.log(`wrote ${OUT} (${Math.ceil(x)}×${Math.ceil(box.y2 - box.y1)})`);
